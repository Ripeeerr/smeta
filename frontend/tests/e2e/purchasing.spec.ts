import { expect, test, type Page } from '@playwright/test'

async function login(page: Page, username: string) {
  await page.goto('/login')
  await page.getByLabel('Логин', { exact: true }).fill(username)
  await page.getByLabel('Пароль', { exact: true }).fill(process.env.DEMO_PASSWORD!)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Обзор', exact: true })).toBeVisible()
}

async function logout(page: Page) {
  await page.getByRole('button', { name: 'Выйти из профиля', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Войти в пространство' })).toBeVisible()
}

test('сотрудник создаёт заявку, руководитель согласует, закупщик оформляет и принимает заказ', async ({ page }) => {
  const title = `Монитор для нового сотрудника ${Date.now()}`
  await login(page, 'employee')
  await page.getByRole('link', { name: 'Создать заявку' }).click()
  await page.getByLabel('Что нужно закупить').fill(title)
  const date = new Date(); date.setDate(date.getDate() + 10)
  await page.getByLabel('Нужно получить к').fill(date.toISOString().slice(0, 10))
  await page.getByLabel('Обоснование').fill('Нужно оборудовать рабочее место нового сотрудника отдела продаж.')
  await page.getByLabel('Позиция 1', { exact: true }).fill('Монитор 27 дюймов')
  await page.getByLabel('Кол-во', { exact: true }).fill('2')
  await page.getByLabel('Цена, ₽', { exact: true }).fill('100')
  await page.getByRole('button', { name: 'Сохранить черновик' }).click()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  const url = page.url()
  await page.getByRole('button', { name: 'На согласование', exact: true }).click()
  await expect(page.locator('.detail-number .badge')).toHaveText('На согласовании')
  await logout(page)
  await login(page, 'manager')
  await page.goto(url)
  await page.getByRole('button', { name: 'Согласовать', exact: true }).click()
  await expect(page.locator('.detail-number .badge')).toHaveText('К закупке')
  await logout(page)
  await login(page, 'buyer')
  await page.goto(url)
  await page.getByRole('button', { name: 'Добавить', exact: true }).click()
  await page.getByLabel('Поставщик', { exact: true }).selectOption({ label: 'ООО «ТехноПроф»' })
  await page.getByLabel('Общая сумма, ₽').fill('180')
  await page.getByLabel('Доставка, дней').fill('3')
  await page.getByRole('button', { name: 'Подтвердить', exact: true }).click()
  await expect(page.locator('.quote-list')).toContainText('ТехноПроф')
  await page.getByRole('button', { name: 'Оформить закупку', exact: true }).click()
  await page.getByLabel('Предложение', { exact: true }).selectOption({ index: 1 })
  await page.getByLabel('Ожидаемая дата поставки').fill(date.toISOString().slice(0, 10))
  await page.getByRole('button', { name: 'Подтвердить', exact: true }).click()
  await expect(page.locator('.detail-number .badge')).toHaveText('В пути')
  await page.getByRole('button', { name: 'Принять товары', exact: true }).click()
  await page.getByRole('spinbutton').fill('1')
  await page.getByRole('button', { name: 'Подтвердить', exact: true }).click()
  await expect(page.getByText('Получено 1 из 2')).toBeVisible()
  await page.getByRole('button', { name: 'Принять товары', exact: true }).click()
  await page.getByRole('button', { name: 'Подтвердить', exact: true }).click()
  await expect(page.locator('.detail-number .badge')).toHaveText('Получено')
})

test('светлая тема сохраняется, выход завершает сессию', async ({ page }) => {
  await login(page, 'director')
  await page.getByRole('button', { name: 'Включить светлую тему' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.getByRole('link', { name: 'Настройки', exact: true }).click()
  await page.getByRole('button', { name: 'Тёмная', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Включить светлую тему' })).toBeVisible()
  await logout(page)
  await page.goto('/requests')
  await expect(page).toHaveURL(/login/)
})

test('мобильное пространство не имеет горизонтального переполнения страницы', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await login(page, 'director')
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Открыть меню' }).click()
  await page.getByRole('link', { name: 'Поставщики', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Поставщики', exact: true })).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('содержимое заявки и комментария отображается как текст', async ({ page }) => {
  await login(page, 'employee')
  const payload = '<img src=x onerror="window.__xss=1">'
  await page.getByRole('link', { name: 'Создать заявку' }).click()
  await page.getByLabel('Что нужно закупить').fill(payload)
  const date = new Date(); date.setDate(date.getDate() + 10)
  await page.getByLabel('Нужно получить к').fill(date.toISOString().slice(0, 10))
  await page.getByLabel('Обоснование').fill(payload)
  await page.getByLabel('Позиция 1', { exact: true }).fill(payload)
  await page.getByLabel('Цена, ₽', { exact: true }).fill('10')
  await page.getByRole('button', { name: 'Сохранить черновик' }).click()
  await expect(page.getByRole('heading', { name: payload, exact: true })).toBeVisible()
  await page.getByLabel('Комментарий', { exact: true }).fill(payload)
  await page.getByRole('button', { name: 'Отправить комментарий' }).click()
  await expect(page.locator('.timeline')).toContainText(payload)
  expect(await page.evaluate(() => Reflect.get(window, '__xss'))).toBeUndefined()
  await expect(page.locator('img[src="x"]')).toHaveCount(0)
})
